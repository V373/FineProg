"""
t-SNE visualization of TCC embeddings colored by phase labels.

Reads ``datasets/embeddings/{run_name}/embd_tsne_phase_label.h5`` (generated by
evaluate.py with ``gen_tsne_phase_label: true``).

Three groups are distinguished by the per-video attributes ``data_type`` and
``is_ground_truth`` stored in that H5 file:

  ┌─────────────────────────────────────┬──────────────┐
  │ Group                               │ Color scheme │
  ├─────────────────────────────────────┼──────────────┤
  │ Training — ground-truth phase label │ Purple       │
  │ Training — SVM-predicted label      │ Blue         │
  │ Validation (any label origin)       │ Red          │
  └─────────────────────────────────────┴──────────────┘

Within each group the 5 phase labels (0–4) are mapped to 5 gradient bins
from light (phase 0) to dark (phase 4).

Usage:
    cd /home/user/zhangzk/projects/fineprog
    python scripts/visualize_embeddings_tsne_phase.py \\
    [--viz_config configs_v2/visualize/tsne_phase.yaml] \
    [--embedding_ref can_ph_valid_ep50k]
"""

